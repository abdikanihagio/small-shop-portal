// PostgreSQL tables. Every statement checks what already exists, so running this on every start is safe.
// Conventions:
// - money is whole cents (BIGINT); flags are INTEGER 1 / 0;
// - dates are local time text "YYYY-MM-DD HH:MM:SS" (expenses.date is "YYYY-MM-DD");
// - usernames, SKUs and role names are unique ignoring upper/lower case.
const { DEFAULT_SETTINGS, PAYMENT_REFS } = require('../config/constants');

const NOW = "to_char(now(), 'YYYY-MM-DD HH24:MI:SS')";
const ID = 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';

const TABLES = `
  CREATE TABLE IF NOT EXISTS roles (
    ${ID},
    name TEXT NOT NULL,
    permissions TEXT NOT NULL DEFAULT '[]',
    builtin INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT ${NOW}
  );
  CREATE UNIQUE INDEX IF NOT EXISTS idx_roles_name ON roles (lower(name));

  CREATE TABLE IF NOT EXISTS users (
    ${ID},
    username TEXT NOT NULL,
    name TEXT NOT NULL DEFAULT '',
    role TEXT NOT NULL CHECK (role IN ('admin','staff')),
    role_id INTEGER REFERENCES roles(id),
    is_owner INTEGER NOT NULL DEFAULT 0,
    password_hash TEXT NOT NULL,
    salt TEXT NOT NULL,
    active INTEGER NOT NULL DEFAULT 1,
    -- Two-step login: totp_pending holds a secret while it is being set up;
    -- recovery_codes is a JSON list of SHA-256 hashes of unused recovery codes.
    totp_secret TEXT,
    totp_pending TEXT,
    totp_enabled INTEGER NOT NULL DEFAULT 0,
    totp_last_step BIGINT NOT NULL DEFAULT -1,
    recovery_codes TEXT NOT NULL DEFAULT '[]',
    created_at TEXT NOT NULL DEFAULT ${NOW}
  );
  CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username ON users (lower(username));

  -- Only a SHA-256 hash of the sign-in token is stored, so a copy of the database cannot be used to sign in.
  CREATE TABLE IF NOT EXISTS sessions (
    token TEXT PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at BIGINT NOT NULL,
    last_seen BIGINT
  );

  CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
  );

  CREATE TABLE IF NOT EXISTS products (
    ${ID},
    sku TEXT NOT NULL,
    name TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT '',
    unit TEXT NOT NULL DEFAULT 'pcs',
    cost_cents BIGINT NOT NULL DEFAULT 0,
    price_cents BIGINT NOT NULL DEFAULT 0,
    stock INTEGER NOT NULL DEFAULT 0,
    reorder_level INTEGER NOT NULL DEFAULT 0,
    active INTEGER NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL DEFAULT ${NOW}
  );
  CREATE UNIQUE INDEX IF NOT EXISTS idx_products_sku ON products (lower(sku));

  CREATE TABLE IF NOT EXISTS customers (
    ${ID},
    name TEXT NOT NULL,
    phone TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL DEFAULT '',
    address TEXT NOT NULL DEFAULT '',
    id_number TEXT NOT NULL DEFAULT '',
    credit_limit_cents BIGINT NOT NULL DEFAULT 0,
    notes TEXT NOT NULL DEFAULT '',
    active INTEGER NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL DEFAULT ${NOW}
  );

  CREATE TABLE IF NOT EXISTS suppliers (
    ${ID},
    name TEXT NOT NULL,
    contact_person TEXT NOT NULL DEFAULT '',
    phone TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL DEFAULT '',
    address TEXT NOT NULL DEFAULT '',
    tax_id TEXT NOT NULL DEFAULT '',
    notes TEXT NOT NULL DEFAULT '',
    active INTEGER NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL DEFAULT ${NOW}
  );

  CREATE TABLE IF NOT EXISTS sales (
    ${ID},
    customer TEXT NOT NULL DEFAULT '',
    customer_id INTEGER REFERENCES customers(id),
    payment_method TEXT NOT NULL DEFAULT 'cash',
    subtotal_cents BIGINT NOT NULL,
    discount_cents BIGINT NOT NULL DEFAULT 0,
    -- Set when the discount was given as a percentage (discount_cents still holds the money value).
    discount_percent DOUBLE PRECISION,
    tax_cents BIGINT NOT NULL DEFAULT 0,
    total_cents BIGINT NOT NULL,
    cogs_cents BIGINT NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'completed' CHECK (status IN ('completed','void')),
    user_id INTEGER REFERENCES users(id),
    created_at TEXT NOT NULL DEFAULT ${NOW}
  );

  CREATE TABLE IF NOT EXISTS sale_items (
    ${ID},
    sale_id INTEGER NOT NULL REFERENCES sales(id) ON DELETE CASCADE,
    product_id INTEGER NOT NULL REFERENCES products(id),
    name TEXT NOT NULL,
    qty INTEGER NOT NULL,
    price_cents BIGINT NOT NULL,
    cost_cents BIGINT NOT NULL
  );

  -- One stock delivery (it can contain many products, see stock_movements.purchase_id).
  CREATE TABLE IF NOT EXISTS purchases (
    ${ID},
    supplier_id INTEGER REFERENCES suppliers(id),
    supplier TEXT NOT NULL DEFAULT '',
    invoice TEXT NOT NULL DEFAULT '',
    payment_method TEXT NOT NULL DEFAULT 'cash',
    total_cents BIGINT NOT NULL,
    user_id INTEGER REFERENCES users(id),
    created_at TEXT NOT NULL DEFAULT ${NOW}
  );

  -- Items brought back from a sale. A sale can have several returns until everything is back.
  -- Money amounts are this return's share of the sale (so all returns together never exceed it).
  CREATE TABLE IF NOT EXISTS returns (
    ${ID},
    ref TEXT,
    sale_id INTEGER NOT NULL REFERENCES sales(id),
    customer_id INTEGER REFERENCES customers(id),
    refund_method TEXT NOT NULL,               -- cash | card | mobile | credit (taken off the customer's account)
    subtotal_cents BIGINT NOT NULL,            -- items at the price sold
    discount_cents BIGINT NOT NULL DEFAULT 0,
    tax_cents BIGINT NOT NULL DEFAULT 0,
    total_cents BIGINT NOT NULL,               -- refund = subtotal - discount + tax
    cogs_cents BIGINT NOT NULL DEFAULT 0,      -- cost of all returned items
    written_off_cents BIGINT NOT NULL DEFAULT 0, -- cost of damaged items not put back in stock
    reason TEXT NOT NULL DEFAULT '',
    user_id INTEGER REFERENCES users(id),
    created_at TEXT NOT NULL DEFAULT ${NOW}
  );

  CREATE TABLE IF NOT EXISTS return_items (
    ${ID},
    return_id INTEGER NOT NULL REFERENCES returns(id),
    sale_item_id INTEGER NOT NULL REFERENCES sale_items(id),
    product_id INTEGER NOT NULL REFERENCES products(id),
    name TEXT NOT NULL,
    qty INTEGER NOT NULL,
    price_cents BIGINT NOT NULL,
    cost_cents BIGINT NOT NULL,
    restocked INTEGER NOT NULL DEFAULT 1
  );

  CREATE TABLE IF NOT EXISTS stock_movements (
    ${ID},
    product_id INTEGER NOT NULL REFERENCES products(id),
    type TEXT NOT NULL CHECK (type IN ('opening','purchase','adjustment','sale','void','return')),
    qty_change INTEGER NOT NULL,
    unit_cost_cents BIGINT NOT NULL DEFAULT 0,
    supplier TEXT NOT NULL DEFAULT '',
    note TEXT NOT NULL DEFAULT '',
    sale_id INTEGER REFERENCES sales(id),
    purchase_id INTEGER REFERENCES purchases(id),
    return_id INTEGER REFERENCES returns(id),
    user_id INTEGER REFERENCES users(id),
    created_at TEXT NOT NULL DEFAULT ${NOW}
  );

  -- Payments and expenses are never deleted; mistakes are reversed and stay visible.
  CREATE TABLE IF NOT EXISTS customer_payments (
    ${ID},
    ref TEXT,
    customer_id INTEGER NOT NULL REFERENCES customers(id),
    amount_cents BIGINT NOT NULL,
    method TEXT NOT NULL DEFAULT 'cash',
    note TEXT NOT NULL DEFAULT '',
    user_id INTEGER REFERENCES users(id),
    created_at TEXT NOT NULL DEFAULT ${NOW},
    reversed_at TEXT,
    reversed_by INTEGER REFERENCES users(id),
    reverse_reason TEXT NOT NULL DEFAULT ''
  );

  CREATE TABLE IF NOT EXISTS supplier_payments (
    ${ID},
    ref TEXT,
    supplier_id INTEGER NOT NULL REFERENCES suppliers(id),
    amount_cents BIGINT NOT NULL,
    method TEXT NOT NULL DEFAULT 'cash',
    note TEXT NOT NULL DEFAULT '',
    user_id INTEGER REFERENCES users(id),
    created_at TEXT NOT NULL DEFAULT ${NOW},
    reversed_at TEXT,
    reversed_by INTEGER REFERENCES users(id),
    reverse_reason TEXT NOT NULL DEFAULT ''
  );

  CREATE TABLE IF NOT EXISTS expenses (
    ${ID},
    date TEXT NOT NULL,
    category TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    amount_cents BIGINT NOT NULL,
    payment_method TEXT NOT NULL DEFAULT 'cash',
    user_id INTEGER REFERENCES users(id),
    created_at TEXT NOT NULL DEFAULT ${NOW},
    reversed_at TEXT,
    reversed_by INTEGER REFERENCES users(id),
    reverse_reason TEXT NOT NULL DEFAULT ''
  );

  -- Append-only record of who did what (logins, money, prices, users, settings).
  CREATE TABLE IF NOT EXISTS audit_log (
    ${ID},
    created_at TEXT NOT NULL DEFAULT ${NOW},
    user_id INTEGER REFERENCES users(id),
    username TEXT NOT NULL DEFAULT '',
    action TEXT NOT NULL,
    entity TEXT NOT NULL DEFAULT '',
    entity_id TEXT NOT NULL DEFAULT '',
    details TEXT NOT NULL DEFAULT '',
    ip TEXT NOT NULL DEFAULT ''
  );

  -- The shop's logo and browser-tab icon (uploaded in Settings).
  CREATE TABLE IF NOT EXISTS branding (
    kind TEXT PRIMARY KEY CHECK (kind IN ('logo','icon')),
    mime TEXT NOT NULL,
    data BYTEA NOT NULL,
    updated_at TEXT NOT NULL
  );

  -- Cash closing: a cashier's shift at the till, from the opening float to the counted cash.
  -- summary holds the closing figures (JSON) so the Z-report never changes afterwards.
  CREATE TABLE IF NOT EXISTS cash_shifts (
    ${ID},
    user_id INTEGER NOT NULL REFERENCES users(id),
    status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','closed')),
    opened_at TEXT NOT NULL DEFAULT ${NOW},
    opening_float_cents BIGINT NOT NULL DEFAULT 0,
    -- The last record of each kind (sales, payments, …) when the shift opened / closed: the shift
    -- covers exactly the records in between (no clock-precision edge cases).
    start_ids TEXT NOT NULL DEFAULT '{}',
    end_ids TEXT,
    closed_at TEXT,
    closed_by INTEGER REFERENCES users(id),
    expected_cents BIGINT,
    counted_cents BIGINT,
    difference_cents BIGINT,
    summary TEXT NOT NULL DEFAULT '{}',
    note TEXT NOT NULL DEFAULT ''
  );
  CREATE UNIQUE INDEX IF NOT EXISTS idx_shifts_one_open ON cash_shifts(user_id) WHERE status = 'open';
  -- When a sale is voided: when, by whom, and in which open shift (the cash is paid back from that drawer).
  ALTER TABLE sales ADD COLUMN IF NOT EXISTS voided_at TEXT;
  ALTER TABLE sales ADD COLUMN IF NOT EXISTS voided_by INTEGER REFERENCES users(id);
  ALTER TABLE sales ADD COLUMN IF NOT EXISTS voided_in_shift INTEGER REFERENCES cash_shifts(id);
  CREATE INDEX IF NOT EXISTS idx_shifts_opened ON cash_shifts(opened_at);

  -- Expiry dates: stock received with an expiry date is a batch. Sales take from the batch that
  -- expires first; qty_left is what is still on the shelf from that batch.
  CREATE TABLE IF NOT EXISTS stock_batches (
    ${ID},
    product_id INTEGER NOT NULL REFERENCES products(id),
    expiry_date TEXT NOT NULL,
    qty_received INTEGER NOT NULL,
    qty_left INTEGER NOT NULL CHECK (qty_left >= 0),
    unit_cost_cents BIGINT NOT NULL DEFAULT 0,
    purchase_id INTEGER REFERENCES purchases(id),
    user_id INTEGER REFERENCES users(id),
    created_at TEXT NOT NULL DEFAULT ${NOW}
  );
  CREATE INDEX IF NOT EXISTS idx_batches_product ON stock_batches(product_id, expiry_date);
  -- When the batch was made (optional; entered with a new product's opening stock).
  ALTER TABLE stock_batches ADD COLUMN IF NOT EXISTS production_date TEXT;
  -- Which batches each sold line came from ([{ "id": batch, "qty": n }]), so voids and returns put them back.
  ALTER TABLE sale_items ADD COLUMN IF NOT EXISTS batches TEXT NOT NULL DEFAULT '[]';

  CREATE UNIQUE INDEX IF NOT EXISTS idx_customer_payments_ref ON customer_payments(ref);
  CREATE UNIQUE INDEX IF NOT EXISTS idx_supplier_payments_ref ON supplier_payments(ref);
  CREATE UNIQUE INDEX IF NOT EXISTS idx_returns_ref ON returns(ref);
  CREATE INDEX IF NOT EXISTS idx_sales_created ON sales(created_at);
  CREATE INDEX IF NOT EXISTS idx_sales_customer ON sales(customer_id, created_at);
  CREATE INDEX IF NOT EXISTS idx_items_sale ON sale_items(sale_id);
  CREATE INDEX IF NOT EXISTS idx_returns_sale ON returns(sale_id);
  CREATE INDEX IF NOT EXISTS idx_returns_created ON returns(created_at);
  CREATE INDEX IF NOT EXISTS idx_return_items_sale_item ON return_items(sale_item_id);
  CREATE INDEX IF NOT EXISTS idx_moves_product ON stock_movements(product_id, created_at);
  CREATE INDEX IF NOT EXISTS idx_purchases_supplier ON purchases(supplier_id, created_at);
  CREATE INDEX IF NOT EXISTS idx_spayments_supplier ON supplier_payments(supplier_id, created_at);
  CREATE INDEX IF NOT EXISTS idx_payments_customer ON customer_payments(customer_id, created_at);
  CREATE INDEX IF NOT EXISTS idx_expenses_date ON expenses(date);
  CREATE INDEX IF NOT EXISTS idx_audit_created ON audit_log(created_at);

  -- The database itself refuses to change or delete activity-log rows.
  CREATE OR REPLACE FUNCTION audit_log_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
  BEGIN
    RAISE EXCEPTION 'audit log is append-only';
  END $$;
  DROP TRIGGER IF EXISTS audit_log_no_change ON audit_log;
  CREATE TRIGGER audit_log_no_change BEFORE UPDATE OR DELETE OR TRUNCATE ON audit_log
    FOR EACH STATEMENT EXECUTE FUNCTION audit_log_append_only();
`;

async function migrate(db) {
  await db.exec(TABLES);

  // Roles for non-admin accounts (see src/config/permissions.js). Admins always have every permission.
  // "Cashier" is built in (can be edited, not deleted); "Supply chain" is a ready-made example.
  if (!(await db.get('SELECT 1 FROM roles WHERE builtin = 1'))) {
    await db.run("INSERT INTO roles (name, permissions, builtin) VALUES ('Cashier', ?, 1)", JSON.stringify(['sell', 'sales.view', 'products.view', 'inventory.view']));
    await db.run(
      "INSERT INTO roles (name, permissions) VALUES ('Supply chain', ?) ON CONFLICT DO NOTHING",
      JSON.stringify(['products.view', 'products.manage', 'costs.view', 'inventory.view', 'inventory.manage', 'suppliers.manage'])
    );
  }

  // Shop settings and reference-number counters (existing values are kept).
  const settings = { ...DEFAULT_SETTINGS, ...Object.fromEntries(PAYMENT_REFS.map((r) => [r.counter, '0'])), sys_sessions_hashed: '1' };
  for (const [k, v] of Object.entries(settings)) await db.run('INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT (key) DO NOTHING', k, v);
}

module.exports = { migrate, NOW };
